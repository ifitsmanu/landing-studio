import assert from "node:assert/strict";
import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import test from "node:test";

import {
  buildOpenAiMetadata,
  serializeOpenAiMetadata,
} from "../scripts/generate-openai-metadata.mjs";
import { validateRepository } from "../scripts/validate-repo.mjs";

const COMMUNITY_FILES = [
  "README.md",
  "CHANGELOG.md",
  "CITATION.cff",
  "CODE_OF_CONDUCT.md",
  "CONTRIBUTING.md",
  "GOVERNANCE.md",
  "ROADMAP.md",
  "SECURITY.md",
  "SUPPORT.md",
];

const VALID_DESCRIPTION =
  "Audit landing pages for clear answers, accessible evidence, and defensible claims.";

async function put(root, relativePath, contents) {
  const path = join(root, relativePath);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, contents, "utf8");
}

function skillDocument({
  name = "sample-skill",
  description = VALID_DESCRIPTION,
  license = "Apache-2.0",
  extra = "",
} = {}) {
  return `---
name: ${name}
description: ${description}
license: ${license}
metadata:
  author: test
  version: "1.0.0"
${extra}---

# Sample skill

Read the [evidence guide](references/evidence.md) before acting.
`;
}

async function makeRepository() {
  const root = await mkdtemp(join(tmpdir(), "landing-studio-validator-"));

  for (const file of COMMUNITY_FILES) {
    await put(root, file, `# ${file}\n`);
  }
  await put(
    root,
    "LICENSE",
    "Apache License\nVersion 2.0, January 2004\nhttp://www.apache.org/licenses/\n",
  );
  await put(
    root,
    "package.json",
    `${JSON.stringify(
      {
        name: "fixture",
        version: "1.0.0",
        type: "module",
        license: "Apache-2.0",
        scripts: {},
      },
      null,
      2,
    )}\n`,
  );
  await put(
    root,
    ".claude-plugin/plugin.json",
    `${JSON.stringify(
      {
        name: "fixture",
        version: "1.0.0",
        description: "Fixture",
        license: "Apache-2.0",
        skills: "./skills/",
      },
      null,
      2,
    )}\n`,
  );
  await put(root, "skills/sample-skill/references/evidence.md", "# Evidence\n");
  await put(root, "skills/sample-skill/SKILL.md", skillDocument());
  await put(
    root,
    "skills/sample-skill/agents/openai.yaml",
    serializeOpenAiMetadata({
      name: "sample-skill",
      description: VALID_DESCRIPTION,
    }),
  );

  return root;
}

async function errorsFor(root, options = {}) {
  const result = await validateRepository(root, { runTests: false, ...options });
  return result.errors.join("\n");
}

test("generated OpenAI metadata stays within interface limits", () => {
  const metadata = buildOpenAiMetadata({
    name: "sample-skill",
    description:
      "Evaluate a deliberately long landing-page workflow description that cannot fit into the compact interface field without a deterministic, word-safe reduction.",
  });

  assert.ok(metadata.interface.short_description.length >= 25);
  assert.ok(metadata.interface.short_description.length <= 64);
  assert.match(metadata.interface.default_prompt, /\$sample-skill/);
  assert.match(serializeOpenAiMetadata({ name: "sample-skill", description: VALID_DESCRIPTION }), /^# Generated by /);
});

test("accepts a valid skill contract, metadata file, links, and Apache license", async (t) => {
  const root = await makeRepository();
  t.after(() => rm(root, { recursive: true, force: true }));

  const result = await validateRepository(root, { runTests: false });
  assert.deepEqual(result.errors, []);
  assert.equal(result.ok, true);
});

test("ignores generated Landing Studio state and evidence", async (t) => {
  const root = await makeRepository();
  t.after(() => rm(root, { recursive: true, force: true }));

  const before = await validateRepository(root, { runTests: false });
  await put(root, ".landing-studio/evidence/browser-report.json", "{not-json\n");
  await put(root, ".landing-studio/run.yaml", "[not-yaml\n");
  const after = await validateRepository(root, { runTests: false });

  assert.deepEqual(after.errors, []);
  assert.equal(after.checked.files, before.checked.files);
});

test("rejects descriptions longer than the Agent Skills limit", async (t) => {
  const root = await makeRepository();
  t.after(() => rm(root, { recursive: true, force: true }));
  await put(
    root,
    "skills/sample-skill/SKILL.md",
    skillDocument({ description: "x".repeat(1025) }),
  );

  assert.match(await errorsFor(root), /description.*1024/i);
});

test("rejects invalid YAML in frontmatter and repository YAML files", async (t) => {
  const root = await makeRepository();
  t.after(() => rm(root, { recursive: true, force: true }));
  await put(root, "skills/sample-skill/SKILL.md", "---\nname: [\n---\n# Broken\n");
  await put(root, "templates/broken.yaml", "key: [\n");

  const errors = await errorsFor(root);
  assert.match(errors, /SKILL\.md.*YAML/i);
  assert.match(errors, /broken\.yaml.*YAML/i);
});

test("rejects a skill name that does not match its directory", async (t) => {
  const root = await makeRepository();
  t.after(() => rm(root, { recursive: true, force: true }));
  await put(
    root,
    "skills/sample-skill/SKILL.md",
    skillDocument({ name: "different-skill" }),
  );

  assert.match(await errorsFor(root), /name.*directory/i);
});

test("rejects broken relative Markdown links", async (t) => {
  const root = await makeRepository();
  t.after(() => rm(root, { recursive: true, force: true }));
  const path = join(root, "skills/sample-skill/SKILL.md");
  const source = await readFile(path, "utf8");
  await writeFile(
    path,
    source.replace("references/evidence.md", "references/missing.md"),
    "utf8",
  );

  assert.match(await errorsFor(root), /broken.*references\/missing\.md/i);
});

test("rejects missing repository and skill Apache licenses", async (t) => {
  const root = await makeRepository();
  t.after(() => rm(root, { recursive: true, force: true }));
  await rm(join(root, "LICENSE"));
  await put(
    root,
    "skills/sample-skill/SKILL.md",
    skillDocument({ license: "Proprietary" }),
  );

  const errors = await errorsFor(root);
  assert.match(errors, /LICENSE.*missing/i);
  assert.match(errors, /license.*Apache-2\.0/i);
});

test("rejects a placeholder LICENSE that is not the Apache 2.0 grant", async (t) => {
  const root = await makeRepository();
  t.after(() => rm(root, { recursive: true, force: true }));
  await put(root, "LICENSE", "Apache-2.0\n");
  assert.match(await errorsFor(root), /LICENSE.*Apache License 2\.0 text/i);
});

test("landing-studio package validation rejects an incomplete canonical skill inventory", async (t) => {
  const root = await makeRepository();
  t.after(() => rm(root, { recursive: true, force: true }));
  const packageJson = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
  packageJson.name = "landing-studio";
  await put(root, "package.json", `${JSON.stringify(packageJson, null, 2)}\n`);
  assert.match(await errorsFor(root), /required skill is missing/i);
});

test("rejects a canonical template that violates its paired schema", async (t) => {
  const root = await makeRepository();
  t.after(() => rm(root, { recursive: true, force: true }));
  const packageJson = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
  packageJson.name = "landing-studio";
  await put(root, "package.json", `${JSON.stringify(packageJson, null, 2)}\n`);
  await put(root, "schemas/run.schema.json", `${JSON.stringify({ type: "object", required: ["required_field"] })}\n`);
  await put(root, "templates/run.yaml", "different: value\n");
  assert.match(await errorsFor(root), /templates\/run\.yaml.*schema/i);
});

test("rejects stale generated metadata after its skill contract changes", async (t) => {
  const root = await makeRepository();
  t.after(() => rm(root, { recursive: true, force: true }));
  await put(
    root,
    "skills/sample-skill/SKILL.md",
    skillDocument({
      description: "Design accessible landing-page sections from approved evidence and tokens.",
    }),
  );

  assert.match(await errorsFor(root), /openai\.yaml.*stale/i);
});

test("fails validation when the executable unit-test command fails", async (t) => {
  const root = await makeRepository();
  t.after(() => rm(root, { recursive: true, force: true }));
  await put(
    root,
    "package.json",
    `${JSON.stringify(
      {
        name: "fixture",
        version: "1.0.0",
        type: "module",
        license: "Apache-2.0",
        scripts: { test: "node -e \"process.exit(7)\"" },
      },
      null,
      2,
    )}\n`,
  );

  const result = await validateRepository(root, { runTests: true });
  assert.equal(result.ok, false);
  assert.match(result.errors.join("\n"), /test command failed/i);
});
